<?php

declare(strict_types=1);

namespace CajeerEngine\Installer;

use Symfony\Component\Dotenv\Dotenv;

/** Install-time configuration writer. Validate the complete document before replacing it. */
final readonly class InstallerEnvironment
{
    public function __construct(private string $path) {}

    public function read(): array
    {
        if (!is_file($this->path)) return [];
        return (new Dotenv())->parse((string) file_get_contents($this->path), $this->path);
    }

    public function write(array $values, string $example): array
    {
        if (is_link($this->path)) throw new \RuntimeException('Unsafe .env symlink');
        $created = !is_file($this->path);
        $old = $created ? [] : $this->read();
        $base = $created ? (new Dotenv())->parse((string) file_get_contents($example), $example) : $old;
        $merged = array_replace($base, $values);
        $body = "# Generated by CajeerEngine Forum installer\n";
        foreach ($merged as $key => $value) {
            if (!preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/D', $key) || preg_match('/[\x00\r\n]/', $value)) {
                throw new \InvalidArgumentException('Unsupported multiline environment value: '.$key);
            }
            // Single quoted literals are not expanded by Symfony Dotenv. Escape
            // apostrophes with a separate double-quoted fragment.
            $encoded = preg_match('~^[A-Za-z0-9_./:@%+,=-]*$~D', $value) ? $value : "'".str_replace("'", "'\"'\"'", $value)."'";
            $body .= $key.'='.$encoded."\n";
        }
        if ((new Dotenv())->parse($body, $this->path) !== $merged) throw new \RuntimeException('Environment round-trip failed');
        $tmp = tempnam(dirname($this->path), '.install-env-');
        if ($tmp === false) throw new \RuntimeException('Cannot create environment file');
        try {
            if (!chmod($tmp, 0600) || file_put_contents($tmp, $body, LOCK_EX) !== strlen($body) || !rename($tmp, $this->path)) {
                throw new \RuntimeException('Cannot save environment file');
            }
        } finally { if (is_file($tmp)) unlink($tmp); }
        $changed = [];
        foreach ($values as $key => $value) if (($old[$key] ?? null) !== $value) $changed[$key] = true;
        return ['created'=>$created, 'changed'=>$changed];
    }
}
